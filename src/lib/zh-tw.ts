/**
 * 词组表按长度倒序替换，避免「复制」被更短的规则先吃掉。
 * 逐字表只处理剩下的单字。
 */
const PHRASES_SORTED = [...PHRASES].sort((a, b) => b[0].length - a[0].length)
const VOCAB_SORTED = [...TAIWAN_VOCAB].sort((a, b) => b[0].length - a[0].length)

/** 把一段简体中文转成「繁體中文（台灣用語）」 */
export function toTraditionalTW(input: string): string {
  if (!input) return input
  let s = input

  for (const [from, to] of PHRASES_SORTED) {
    if (from !== to && s.includes(from)) s = s.split(from).join(to)
  }

  let out = ''
  for (const ch of s) {
    out += CHARS[ch] ?? ch
  }
  s = out

  for (const [from, to] of VOCAB_SORTED) {
    if (from !== to && s.includes(from)) s = s.split(from).join(to)
  }
  return s
}

/** 带缓存的转换：同一段文案只转一次（课程数据有 4 万多字，不能每次渲染都重算） */
const cache = new Map<string, string>()

export function tw(input: string): string {
  if (!input) return input
  const hit = cache.get(input)
  if (hit !== undefined) return hit
  const v = toTraditionalTW(input)
  // 简单上限，避免长时间使用后无限膨胀
  if (cache.size > 20000) cache.clear()
  cache.set(input, v)
  return v
}

/** 递归地把一个 JSON 结构里所有字符串转成台灣繁體（用于课程数据） */
export function twDeep<T>(value: T): T {
  if (typeof value === 'string') return tw(value) as unknown as T
  if (Array.isArray(value)) return value.map((x) => twDeep(x)) as unknown as T
  if (value && typeof value === 'object') {
    const out: Record<string, unknown> = {}
    for (const [k, v] of Object.entries(value as Record<string, unknown>)) {
      out[k] = twDeep(v)
    }
    return out as T
  }
  return value
}
